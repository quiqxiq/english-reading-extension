export interface CaptionTrack {
  baseUrl: string;
  name: string;
  languageCode: string;
  isAutoGenerated: boolean;
  vssId: string;
}

export interface SubtitleCue {
  id: number;
  start: number; // in seconds
  duration: number; // in seconds
  end: number; // in seconds
  text: string;
}

export class YouTubeCaptionService {
  /**
   * Extracts the 11-character video ID from a YouTube URL.
   */
  static extractVideoId(url: string = window.location.href): string | null {
    try {
      const u = new URL(url);
      if (u.hostname.includes('youtube.com')) {
        return u.searchParams.get('v');
      }
      if (u.hostname.includes('youtu.be')) {
        return u.pathname.slice(1).split('?')[0] || null;
      }
    } catch {
      // Ignore URL parsing errors
    }
    return null;
  }

  /**
   * Finds available caption tracks for the current video.
   */
  static async getAvailableTracks(videoId: string): Promise<CaptionTrack[]> {
    // 1. Try accessing YouTube player object in page
    const tracksFromPage = this.getTracksFromWindow();
    if (tracksFromPage && tracksFromPage.length > 0) {
      return tracksFromPage;
    }

    // 2. Fallback: fetch watch page HTML and parse ytInitialPlayerResponse
    try {
      const response = await fetch(`https://www.youtube.com/watch?v=${videoId}`, {
        credentials: 'include',
      });
      const html = await response.text();
      const match = html.match(/"captionTracks":\s*(\[[^\]]+\])/);
      if (match && match[1]) {
        const rawTracks = JSON.parse(match[1]);
        return this.normalizeTracks(rawTracks);
      }
    } catch (err) {
      console.warn('[EIR YouTube] Failed to fetch caption tracks from page HTML:', err);
    }

    return [];
  }

  /**
   * Reads player response from window / wrappedJSObject (Firefox WebExtension)
   */
  private static getTracksFromWindow(): CaptionTrack[] | null {
    try {
      // In Firefox WebExtension content scripts, window.wrappedJSObject provides access to page variables
      const win = (window as any).wrappedJSObject || window;
      const initialResponse = win.ytInitialPlayerResponse;
      let rawTracks = initialResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;

      if (!rawTracks || rawTracks.length === 0) {
        // Try movie_player element
        const player = document.getElementById('movie_player') as any;
        const playerResponse = player?.wrappedJSObject?.getPlayerResponse?.() || player?.getPlayerResponse?.();
        rawTracks = playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
      }

      if (!rawTracks || rawTracks.length === 0) {
        // Try ytd-watch-flexy component data
        const flexy = document.querySelector('ytd-watch-flexy') as any;
        const flexyData = flexy?.wrappedJSObject?.playerData || flexy?.playerData;
        rawTracks = flexyData?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
      }

      if (rawTracks && Array.isArray(rawTracks)) {
        return this.normalizeTracks(rawTracks);
      }
    } catch (err) {
      console.debug('[EIR YouTube] Error checking window player data:', err);
    }
    return null;
  }

  /**
   * Normalizes raw YouTube caption tracks into strongly typed CaptionTrack array.
   */
  private static normalizeTracks(rawTracks: any[]): CaptionTrack[] {
    return rawTracks.map((t) => {
      let name = 'English';
      if (typeof t.name === 'string') {
        name = t.name;
      } else if (t.name?.simpleText) {
        name = t.name.simpleText;
      } else if (t.name?.runs?.[0]?.text) {
        name = t.name.runs.map((r: any) => r.text).join(' ');
      }

      const isAutoGenerated = t.kind === 'asr' || (t.vssId && t.vssId.startsWith('a.'));
      return {
        baseUrl: t.baseUrl,
        name: isAutoGenerated && !name.toLowerCase().includes('auto') ? `${name} (Auto-generated)` : name,
        languageCode: t.languageCode || 'en',
        isAutoGenerated,
        vssId: t.vssId || '',
      };
    });
  }

  /**
   * Fetches and parses subtitles for a specific track, grouping fragmented words into sentences.
   */
  static async fetchSubtitles(track: CaptionTrack): Promise<SubtitleCue[]> {
    // Attempt 1: Fetch with format json3 for rich timestamp data
    try {
      const url = track.baseUrl.includes('fmt=') ? track.baseUrl : `${track.baseUrl}&fmt=json3`;
      const res = await fetch(url, { credentials: 'include' });
      if (res.ok) {
        const text = await res.text();
        if (text && text.trim().startsWith('{')) {
          const json = JSON.parse(text);
          if (json.events && Array.isArray(json.events)) {
            const parsedCues = this.parseJson3Events(json.events);
            if (parsedCues.length > 0) {
              return this.aggregateCuesIntoSentences(parsedCues, track.isAutoGenerated);
            }
          }
        }
      }
    } catch (err) {
      console.warn('[EIR YouTube] JSON3 timedtext parsing failed, falling back to XML:', err);
    }

    // Attempt 2: Fetch default XML timedtext format
    try {
      const res = await fetch(track.baseUrl, { credentials: 'include' });
      if (res.ok) {
        const xmlText = await res.text();
        const parsedCues = this.parseXmlTimedText(xmlText);
        if (parsedCues.length > 0) {
          return this.aggregateCuesIntoSentences(parsedCues, track.isAutoGenerated);
        }
      }
    } catch (err) {
      console.error('[EIR YouTube] XML timedtext parsing failed:', err);
    }

    return [];
  }

  /**
   * Parses JSON3 timedtext events into raw cue chunks.
   */
  private static parseJson3Events(events: any[]): SubtitleCue[] {
    const cues: SubtitleCue[] = [];
    let idCounter = 1;

    for (const ev of events) {
      if (!ev.segs || !Array.isArray(ev.segs)) continue;

      const text = ev.segs
        .map((s: any) => s.utf8 || '')
        .join('')
        .replace(/[\r\n]+/g, ' ')
        .trim();

      if (!text) continue;

      const start = (ev.tStartMs || 0) / 1000;
      const duration = (ev.dDurationMs || 0) / 1000;
      const end = start + Math.max(duration, 0.5);

      cues.push({
        id: idCounter++,
        start,
        duration,
        end,
        text: this.decodeHtmlEntities(text),
      });
    }

    return cues;
  }

  /**
   * Parses XML timedtext into raw cue chunks.
   */
  private static parseXmlTimedText(xmlString: string): SubtitleCue[] {
    const parser = new DOMParser();
    const doc = parser.parseFromString(xmlString, 'text/xml');
    const textNodes = doc.querySelectorAll('text');
    const cues: SubtitleCue[] = [];
    let idCounter = 1;

    textNodes.forEach((node) => {
      const start = parseFloat(node.getAttribute('start') || '0');
      const duration = parseFloat(node.getAttribute('dur') || '1');
      const text = (node.textContent || '').replace(/[\r\n]+/g, ' ').trim();

      if (text) {
        cues.push({
          id: idCounter++,
          start,
          duration,
          end: start + duration,
          text: this.decodeHtmlEntities(text),
        });
      }
    });

    return cues;
  }

  /**
   * Aggregates fragmented speech cues into natural, coherent sentences for shadowing.
   * Auto-generated subtitles often deliver 1-3 words per cue. This groups them logically.
   */
  private static aggregateCuesIntoSentences(rawCues: SubtitleCue[], isAutoGenerated: boolean): SubtitleCue[] {
    if (rawCues.length === 0) return [];

    const result: SubtitleCue[] = [];
    let currentSentence = '';
    let currentStart = rawCues[0].start;
    let currentEnd = rawCues[0].end;
    let cueId = 1;

    for (let i = 0; i < rawCues.length; i++) {
      const cue = rawCues[i];
      const nextCue = rawCues[i + 1];

      if (!currentSentence) {
        currentSentence = cue.text;
        currentStart = cue.start;
        currentEnd = cue.end;
      } else {
        currentSentence += ` ${cue.text}`;
        currentEnd = Math.max(currentEnd, cue.end);
      }

      // Check boundary conditions:
      const hasTerminalPunctuation = /[.!?]$/.test(cue.text.trim());
      const hasSignificantSilence = nextCue && nextCue.start - cue.end > 0.65;
      const isTooLong = currentSentence.split(/\s+/).length >= 12 || (currentEnd - currentStart) >= 4.5;
      const isLast = i === rawCues.length - 1;

      // Grouping decision:
      // If manual subtitle has punctuation, break on punctuation or silence.
      // If ASR (auto), break on silence gap, terminal punctuation, or length limit.
      const shouldBreak =
        isLast ||
        hasTerminalPunctuation ||
        hasSignificantSilence ||
        (isAutoGenerated && isTooLong);

      if (shouldBreak) {
        const cleanedText = currentSentence.replace(/\s+/g, ' ').trim();
        if (cleanedText) {
          result.push({
            id: cueId++,
            start: Math.round(currentStart * 100) / 100,
            end: Math.round(currentEnd * 100) / 100,
            duration: Math.round((currentEnd - currentStart) * 100) / 100,
            text: cleanedText,
          });
        }
        currentSentence = '';
      }
    }

    return result;
  }

  /**
   * Decodes HTML entities like &#39;, &amp;, &quot;.
   */
  private static decodeHtmlEntities(str: string): string {
    const doc = new DOMParser().parseFromString(str, 'text/html');
    return doc.body.textContent || str;
  }
}
